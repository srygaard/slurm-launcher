#!/usr/bin/env -S uv run --script
# /// script
# requires-python = ">=3.12"
# dependencies = []
# ///

# "chmod +x job.py" to run as an executable.

import argparse
import os
import re
import shlex
import shutil
import socket
import subprocess
import sys
import tempfile
from collections.abc import Mapping, Sequence
from enum import StrEnum
from fnmatch import fnmatch
from pathlib import Path
from typing import Literal, NamedTuple, cast, get_args

type Cluster = Literal["mila", "fir", "narval", "nibi", "rorqual", "trillium", "unknown"]


def detect_cluster() -> Cluster:
    cluster = os.environ.get("CC_CLUSTER", "").strip().lower()
    if cluster in get_args(Cluster.__value__):
        return cast(Cluster, cluster)
    if socket.getfqdn().lower().endswith("mila.quebec"):
        return "mila"
    return "unknown"


class Ansi(StrEnum):
    PURPLE = "\033[35m"
    YELLOW = "\033[33m"
    RED = "\033[31m"
    RESET = "\033[0m"


class SbatchResult(NamedTuple):
    job_id: int | None
    returncode: int


def sbatch(script: str) -> SbatchResult:
    """Submit a job script to SLURM, printing any error."""
    try:
        result = subprocess.run(["sbatch", "--parsable"], input=script, capture_output=True, text=True)
    except FileNotFoundError:
        result = subprocess.CompletedProcess([], 127, "", "Must be run on Slurm (sbatch not found).")
    try:
        job_id = int(result.stdout.split(";")[0])
    except ValueError:
        job_id = None
    if result.returncode or not job_id:
        print(f"{Ansi.RED}{result.stderr or result.stdout}{Ansi.RESET}")
    return SbatchResult(job_id, result.returncode)


def git(*args: str, repo: Path = Path(__file__).parent) -> str:
    """Run a git command in repo and return its stdout; raises if git fails or isn't installed."""
    # --no-optional-locks: read-only, so don't race an editor's git for .git/index.lock
    return subprocess.run(["git", "--no-optional-locks", "-C", str(repo), *args],
                          capture_output=True, text=True, check=True).stdout


def git_commit_hash() -> str:
    """
    >>> git_commit_hash()  # clean checkout
    'a1b2c3d'
    >>> git_commit_hash()  # uncommitted changes
    'a1b2c3d-dirty'
    """
    try:
        sha_short = git("rev-parse", "--short", "HEAD").strip()
        dirty = git("status", "--porcelain").strip()
    except (subprocess.CalledProcessError, FileNotFoundError):
        return "unknown"
    return sha_short + ("-dirty" if dirty else "")


def snapshot_code(src: Path, dest: Path, exclude: Sequence[str]) -> int:
    """
    Copy the tracked and untracked files, w/out .gitignore'd files.
    Skips paths where any file or dir name matches an exclude glob, e.g. "*.md" or "tests".
    """
    sub_paths = git("ls-files", "-z", "--cached", "--others", "--exclude-standard", "--deduplicate",
                    repo=src).split("\0")
    count = 0
    for sub_path in filter(None, sub_paths):
        if any(fnmatch(part, pattern) for part in Path(sub_path).parts for pattern in exclude):
            continue
        path = src / sub_path
        if path.is_symlink() or path.is_file():  # skip tracked files deleted from the working tree
            (dest / sub_path).parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, dest / sub_path, follow_symlinks=False)  # keep symlinks as links
            count += 1
    return count



def snapshot_script(dest: Path, script: str, job_id: int) -> None:
    """Store the submitted script, with $SLURM_JOB_ID filled in, for reproducibility."""
    meta = (
        f"# git: {git_commit_hash()}\n"
        f"# argv: {shlex.join(sys.argv)}\n"
        f"# generated by {Path(__file__).absolute()}\n"
    )
    resolved = script.replace("$SLURM_JOB_ID", str(job_id))
    (dest / "job.sh").write_text(f"{resolved}\n{meta}")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Submit a job to SLURM.",
        formatter_class=argparse.ArgumentDefaultsHelpFormatter,
    )
    repo = Path(__file__).parent
    slurm_dir = repo / "slurm"
    scratch = os.environ.get("SCRATCH")
    parser.add_argument("-j", "--jobs-dir", type=lambda p: Path(p).resolve(),
                        default=Path(scratch) / repo.name / "jobs" if scratch else slurm_dir / "jobs",
                        help="Directory for job logs and script snapshot")
    parser.add_argument("-f", "--template", default=str(slurm_dir / "templates" / "{config}.{cluster}.sh"),
                        help="Path to the sbatch template; {config} and {cluster} are replaced automatically.")
    parser.add_argument("-C", "--cluster", default=detect_cluster(),
                        help="Override the cluster instead of using the autodetected name")
    parser.add_argument("-c", "--config", default="default",
                        help="Selects the matching template file name via <config>.<cluster>.sh")
    parser.add_argument("-T", "--time", default="3:00:00",
                        help="The sbatch job time limit (HH:MM:SS)")
    parser.add_argument("-d", "--dependency", type=int, default=None,
                        help="Schedule the job after the specified job ID finishes")
    parser.add_argument("-s", "--snapshot", action="store_true",
                        help="Copy and run code from <jobs-dir>/<job_id>/code when submitting")
    parser.add_argument("--dry-run", action="store_true",
                        help="Print the generated script without submitting")
    parser.add_argument("extra_args", nargs="*",
                        help="Arguments forwarded to script, e.g. `-- --lr 3e-4 --steps 10000`")
    args = parser.parse_args()

    args.template = Path(args.template.format(config=args.config, cluster=args.cluster))

    if not args.template.is_file():
        parser.error(f"Template not found: {args.template}")
    return args


def generate_header(template: Path,
                    dependency: int | None,
                    placeholders: Mapping[str, object]) -> str:
    """Fill in the template's #SBATCH directives, then append the conditional ones."""
    header = template.read_text()
    for key, value in placeholders.items():
        header = header.replace(f"{{{{{key}}}}}", str(value))
    if unknown := re.findall(r"\{\{\s*\w+\s*\}\}", header):
        raise SystemExit(f"{Ansi.RED}Unknown placeholder(s) {', '.join(unknown)} in {template}; "
                         f"available: {', '.join(f'{{{{{k}}}}}' for k in placeholders)}{Ansi.RESET}")
    if not header.endswith("\n"):
        header += "\n"

    if dependency is not None:
        header += f"#SBATCH --dependency=afterany:{dependency}\n"
    return header


def main(args: argparse.Namespace) -> int:
    header = generate_header(args.template, args.dependency, {
        "job_name": f"train-{args.config}",
        "time": args.time,
        "job_dir": f"{args.jobs_dir}/%j",  # Slurm expands %j in --output/--error
    })
    code_dir = f"{args.jobs_dir}/$SLURM_JOB_ID/code" if args.snapshot else Path(__file__).parent
    cwd = f'cd "{code_dir}" || exit 1\n'
    command = shlex.join(["uv", "run", "train.py", *args.extra_args])
    script = f'{header}\n{cwd}\n{command}\n'

    if args.dry_run:
        print(f"[dry-run] not submitting\n\n{Ansi.YELLOW}{script}{Ansi.RESET}\n")
        return 0

    args.jobs_dir.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(dir=args.jobs_dir) as _tmp:
        tmp = Path(_tmp)
        if args.snapshot:
            c = snapshot_code(Path(__file__).parent, tmp / "code", exclude=("*.md", "tests"))
            print(f"Snapshotted {c:_} files.")

        result = sbatch(script)
        if not result.job_id:
            return result.returncode or 1

        job_dir = tmp.rename(args.jobs_dir / str(result.job_id))  # rename first: the job may start any moment

    snapshot_script(job_dir, script, result.job_id)

    print(f"Job {Ansi.PURPLE}{result.job_id}{Ansi.RESET} submitted using {args.config!r}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(parse_args()))
